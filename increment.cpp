// post and pre increment and decrement 
// x++ , ++x , x-- , --x

#include<iostream>
using namespace std;
int main(){
    int x = 10;
    cout<<x<<endl;
    x++; // x = x + 1
    cout<<x<<endl;
}

//  also we used decrement 

#include<iostream>
using namespace std;
int main(){
    int x = 10;
    cout<<x<<endl;
    x--; // x = x + 1
    cout<<x<<endl;
}